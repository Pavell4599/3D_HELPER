def p(text="", indent=True, align=WD_ALIGN_PARAGRAPH.JUSTIFY, bold=False,
      size=14, spacing=1.5, before=0, after=0):
    par = doc.add_paragraph()
    par.alignment = align
    par.paragraph_format.line_spacing = spacing
    par.paragraph_format.first_line_indent = Cm(1.25) if indent else Cm(0)
    par.paragraph_format.space_before = Pt(before)
    par.paragraph_format.space_after = Pt(after)
    r = par.add_run(text)
    r.bold = bold; r.font.size = Pt(size); r.font.name = "Times New Roman"
    return par

def h1(text, new_page=True):
    par = p(text, indent=False, align=WD_ALIGN_PARAGRAPH.LEFT, bold=True,
            before=6, after=12)
    par.paragraph_format.page_break_before = new_page
    return par

def h2(text):
    return p(text, indent=False, align=WD_ALIGN_PARAGRAPH.LEFT, bold=True,
             before=12, after=6)

def bullet(text):
    return p("– " + text, indent=False)

def caption(text):
    return p(text, indent=False, align=WD_ALIGN_PARAGRAPH.LEFT, after=4)

def table(headers, rows, widths, center_cols=()):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for j, htext in enumerate(headers):
        cell = t.rows[0].cells[j]
        cell.width = Cm(widths[j])
        par = cell.paragraphs[0]
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
        par.paragraph_format.line_spacing = 1.0
        r = par.add_run(htext); r.bold = True; r.font.size = Pt(12)
    for row in rows:
        cells = t.add_row().cells
        for j, val in enumerate(row):
            cells[j].width = Cm(widths[j])
            par = cells[j].paragraphs[0]
            par.alignment = (WD_ALIGN_PARAGRAPH.CENTER if j in center_cols
                             else WD_ALIGN_PARAGRAPH.LEFT)
            par.paragraph_format.line_spacing = 1.0
            r = par.add_run(str(val)); r.font.size = Pt(12)
    p("", after=6)
    return t

def note(text):
    return p(text, indent=False, size=12, after=6)

